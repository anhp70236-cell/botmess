import Foundation

public enum StructAndJSONGenerator {
    public static func generateIl2CppHeader(
        to url: URL,
        types: [Il2CppTypeInfo],
        macho: MachOParser?
    ) throws {
        let writer = try BufferedFileWriter(url: url)
        defer { try? writer.close() }

        try writer.writeLine("/* Generated by IPA Dumper Pro v2.0 */")
        try writer.writeLine("#pragma once")
        try writer.writeLine("#include <stdint.h>")
        try writer.writeLine("#include <stdbool.h>")
        try writer.writeLine("")
        try writer.writeLine("typedef void (*Il2CppMethodPointer)();")
        try writer.writeLine("typedef struct Il2CppClass { void* klass; void* monitor; } Il2CppClass;")
        try writer.writeLine("typedef struct Il2CppObject { Il2CppClass* klass; void* monitor; } Il2CppObject;")
        try writer.writeLine("typedef struct System_String_Fields { int32_t _stringLength; uint16_t _firstChar; } System_String_Fields;")
        try writer.writeLine("typedef struct System_String_o { Il2CppClass* klass; void* monitor; System_String_Fields fields; } System_String_o;")
        try writer.writeLine("")

        var seenNames = Set<String>()
        for t in types {
            let cBase = Il2CppTypeResolver.sanitizeCIdentifier(t.fullName)
            if seenNames.contains(cBase) { continue }
            seenNames.insert(cBase)

            let instanceFields = t.fields
                .filter { !$0.isStatic && !$0.isConst && $0.offset >= 0 }
                .sorted { $0.offset < $1.offset }

            try writer.writeLine("typedef struct \(cBase)_Fields {")
            if instanceFields.isEmpty {
                try writer.writeLine("    uint8_t _empty;")
            } else {
                var cursor: Int32 = t.isValueType ? 0 : 0x10
                var padIdx = 0
                for (idx, f) in instanceFields.enumerated() {
                    if f.offset > cursor {
                        let padSize = f.offset - cursor
                        try writer.writeLine("    uint8_t _pad\(padIdx)[\(padSize)];")
                        padIdx += 1
                    }
                    let cType = Il2CppTypeResolver.toCTypeName(f.typeName)
                    let fIdent = Il2CppTypeResolver.sanitizeCIdentifier(f.name)
                    try writer.writeLine("    \(cType) \(fIdent); // 0x\(String(f.offset, radix: 16, uppercase: true))")
                    let nextOffset = (idx + 1 < instanceFields.count) ? instanceFields[idx + 1].offset : (f.offset + 8)
                    cursor = max(f.offset + 1, min(f.offset + 8, nextOffset))
                }
            }
            try writer.writeLine("} \(cBase)_Fields;")
            try writer.writeLine("typedef struct \(cBase)_o {")
            if !t.isValueType {
                try writer.writeLine("    Il2CppClass* klass;")
                try writer.writeLine("    void* monitor;")
            }
            try writer.writeLine("    \(cBase)_Fields fields;")
            try writer.writeLine("} \(cBase)_o;")
            try writer.writeLine("")
        }

        if types.isEmpty, let macho = macho {
            for cls in macho.objcClasses {
                let cBase = Il2CppTypeResolver.sanitizeCIdentifier(cls.name)
                if seenNames.contains(cBase) { continue }
                seenNames.insert(cBase)
                try writer.writeLine("typedef struct \(cBase)_ObjC {")
                try writer.writeLine("    void* isa;")
                for iv in cls.ivars {
                    let fIdent = Il2CppTypeResolver.sanitizeCIdentifier(iv.name)
                    try writer.writeLine("    void* \(fIdent); // 0x\(String(iv.offset, radix: 16, uppercase: true))")
                }
                try writer.writeLine("} \(cBase)_ObjC;")
            }
        }

        try writer.close()
    }

    public static func generateScriptJSON(
        to url: URL,
        types: [Il2CppTypeInfo],
        stringLiterals: [Il2CppStringLiteral],
        macho: MachOParser?
    ) throws {
        let writer = try BufferedFileWriter(url: url)
        defer { try? writer.close() }

        try writer.writeLine("{")
        try writer.writeLine("  \"ScriptMethod\": [")

        var methodEntries: [(addr: UInt64, name: String, sig: String, tdSig: String)] = []
        var addresses: [UInt64] = []

        for t in types {
            for m in t.methods where m.rva > 0 {
                let fullSig = "\(m.returnTypeName) \(t.fullName)__\(m.name)(\(m.parameters.map { "\($0.typeName) \($0.name)" }.joined(separator: ", ")))"
                let name = "\(t.fullName)$$\(m.name)"
                methodEntries.append((m.rva, name, fullSig, "\(Il2CppTypeResolver.sanitizeCIdentifier(t.fullName))_o*"))
                addresses.append(m.rva)
            }
        }

        if methodEntries.isEmpty, let macho = macho {
            for cls in macho.objcClasses {
                for m in cls.methods where m.rva > 0 {
                    methodEntries.append((m.rva, "\(cls.name)$$\(m.name)", "void \(cls.name)_\(m.name)()", "void*"))
                    addresses.append(m.rva)
                }
            }
            for sym in macho.exportedSymbols where sym.rva > 0 {
                methodEntries.append((sym.rva, sym.name, sym.name, "void*"))
                addresses.append(sym.rva)
            }
        }

        for (idx, item) in methodEntries.enumerated() {
            let comma = (idx + 1 < methodEntries.count) ? "," : ""
            try writer.writeLine("    {")
            try writer.writeLine("      \"Address\": \(item.addr),")
            try writer.writeLine("      \"Name\": \"\(jsonEscape(item.name))\",")
            try writer.writeLine("      \"Signature\": \"\(jsonEscape(item.sig))\",")
            try writer.writeLine("      \"TypeSignature\": \"\(jsonEscape(item.tdSig))\"")
            try writer.writeLine("    }\(comma)")
        }
        try writer.writeLine("  ],")

        try writer.writeLine("  \"ScriptString\": [")
        var strCount = 0
        let addressableStrings = stringLiterals.filter { $0.address > 0 }
        for (idx, sl) in addressableStrings.enumerated() {
            let comma = (idx + 1 < addressableStrings.count) ? "," : ""
            try writer.writeLine("    {")
            try writer.writeLine("      \"Address\": \(sl.address),")
            try writer.writeLine("      \"Value\": \"\(jsonEscape(sl.value))\"")
            try writer.writeLine("    }\(comma)")
            strCount += 1
        }
        _ = strCount
        try writer.writeLine("  ],")

        try writer.writeLine("  \"ScriptMetadata\": [],")
        try writer.writeLine("  \"ScriptMetadataMethod\": [],")
        let addrList = addresses.map { String($0) }.joined(separator: ", ")
        try writer.writeLine("  \"Addresses\": [\(addrList)]")
        try writer.writeLine("}")
        try writer.close()
    }

    public static func generateStringLiteralJSON(
        to url: URL,
        stringLiterals: [Il2CppStringLiteral]
    ) throws {
        let writer = try BufferedFileWriter(url: url)
        defer { try? writer.close() }

        try writer.writeLine("[")
        for (idx, sl) in stringLiterals.enumerated() {
            let comma = (idx + 1 < stringLiterals.count) ? "," : ""
            let addrHex = String(format: "0x%llX", sl.address)
            try writer.writeLine("  {\"index\": \(sl.index), \"address\": \"\(addrHex)\", \"value\": \"\(jsonEscape(sl.value))\"}\(comma)")
        }
        try writer.writeLine("]")
        try writer.close()
    }

    public static func jsonEscape(_ s: String) -> String {
        var out = ""
        out.reserveCapacity(s.count + 8)
        for u in s.unicodeScalars {
            switch u.value {
            case 0x22: out += "\\\""
            case 0x5C: out += "\\\\"
            case 0x08: out += "\\b"
            case 0x0C: out += "\\f"
            case 0x0A: out += "\\n"
            case 0x0D: out += "\\r"
            case 0x09: out += "\\t"
            case 0x00..<0x20:
                out += String(format: "\\u%04x", u.value)
            default:
                out.append(Character(u))
            }
        }
        return out
    }
}
