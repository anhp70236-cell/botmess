import Foundation

public enum DumpCSGenerator {
    public static func generate(
        to url: URL,
        images: [Il2CppImageInfo],
        types: [Il2CppTypeInfo],
        macho: MachOParser?,
        snapshots: [NativeBinarySnapshot] = [],
        diagnostics: ProtectionDiagnostics,
        options: DumpOptions
    ) throws {
        let writer = try BufferedFileWriter(url: url)
        defer { try? writer.close() }

        try writer.writeLine("// Generated by IPA Dumper Pro v2.0 (Static Analyzer)")
        try writer.writeLine("// Metadata Status: \(diagnostics.metadataStatus.summaryText)")
        if let macho = macho {
            try writer.writeLine("// Mach-O: \(macho.sourceName) (\(macho.architecture)) BaseVM=0x\(String(macho.baseVM, radix: 16, uppercase: true)) FairPlay=\(macho.fairPlayEncrypted ? "Encrypted(cryptid=\(macho.cryptId))" : "Decrypted")")
        }
        try writer.writeLine("// Note: Real-money / In-App Purchase / StoreKit symbols are strictly filtered.")
        try writer.writeLine("")

        if !images.isEmpty {
            for img in images {
                try writer.writeLine("// Image \(img.index): \(img.name) - \(img.typeStart)")
            }
            try writer.writeLine("")
        }

        if !types.isEmpty {
            for t in types {
                try writer.writeLine("// Namespace: \(t.namespace)")
                if let decl = t.declaringTypeName, !decl.isEmpty {
                    try writer.writeLine("// DeclaringType: \(decl)")
                }
                if options.restoreAttributes {
                    for attr in t.attributes {
                        try writer.writeLine("[\(attr.name)]")
                    }
                }

                let kindWord: String
                if t.isInterface { kindWord = "interface" }
                else if t.isEnum { kindWord = "enum" }
                else if t.isValueType { kindWord = "struct" }
                else { kindWord = "class" }

                let vis = visibilityKeyword(t.flags, isNested: t.declaringTypeIndex >= 0)
                var mods = ""
                if !t.isInterface && !t.isValueType && !t.isEnum {
                    if t.isAbstract && t.isSealed { mods += "static " }
                    else if t.isAbstract { mods += "abstract " }
                    else if t.isSealed { mods += "sealed " }
                }

                var displayName = t.name
                if !t.genericParamNames.isEmpty {
                    if let tick = displayName.range(of: "`", options: .backwards) {
                        displayName = String(displayName[..<tick.lowerBound])
                    }
                    displayName += "<\(t.genericParamNames.joined(separator: ", "))>"
                }

                var inheritList: [String] = []
                if t.isEnum {
                    if let valField = t.fields.first(where: { $0.name == "value__" }) {
                        inheritList.append(valField.typeName)
                    }
                } else {
                    if let parent = t.parentName,
                       !parent.isEmpty,
                       parent != "System.Object",
                       parent != "object",
                       parent != "System.ValueType",
                       parent != "System.Enum" {
                        inheritList.append(parent)
                    }
                    for iface in t.interfaceNames where !iface.isEmpty {
                        inheritList.append(iface)
                    }
                }
                let inheritSuffix = inheritList.isEmpty ? "" : " : " + inheritList.joined(separator: ", ")
                let tdComment = options.writeTypeDefIndexes ? " // TypeDefIndex: \(t.typeDefIndex)" : ""

                try writer.writeLine("\(vis) \(mods)\(kindWord) \(displayName)\(inheritSuffix)\(tdComment)")
                try writer.writeLine("{")

                if t.isEnum {
                    if options.includeFields {
                        let enumMembers = t.fields.filter { $0.name != "value__" }
                        for (idx, f) in enumMembers.enumerated() {
                            let val = f.defaultValue ?? "\(idx)"
                            try writer.writeLine("\tpublic const \(t.name) \(f.name) = \(val); // 0x0")
                        }
                    }
                    try writer.writeLine("}")
                    try writer.writeLine("")
                    continue
                }

                if options.includeFields && !t.fields.isEmpty {
                    try writer.writeLine("\t// Fields")
                    for f in t.fields {
                        if options.restoreAttributes {
                            for attr in f.attributes {
                                try writer.writeLine("\t[\(attr.name)]")
                            }
                        }
                        let fVis = fieldVisibility(f.typeAttrs)
                        let fMod = f.isConst ? "const " : (f.isStatic ? "static " : "")
                        let valPart = f.defaultValue.map { " = \($0)" } ?? ""
                        var offComment = ""
                        if options.writeFieldOffsets {
                            if f.offset >= 0 {
                                offComment = String(format: " // 0x%X", f.offset)
                            } else if f.isStatic {
                                offComment = " // 0x0 (static)"
                            } else {
                                offComment = " // 0x0"
                            }
                        }
                        if let ci = f.ctorInitValue {
                            offComment += " [init: \(ci)]"
                        }
                        try writer.writeLine("\t\(fVis) \(fMod)\(f.typeName) \(f.name)\(valPart);\(offComment)")
                    }
                    try writer.writeLine("")
                }

                if options.includeProperties && !t.properties.isEmpty {
                    try writer.writeLine("\t// Properties")
                    for p in t.properties {
                        if options.restoreAttributes {
                            for attr in p.attributes {
                                try writer.writeLine("\t[\(attr.name)]")
                            }
                        }
                        if options.writeMethodOffsets && (p.getRVA > 0 || p.setRVA > 0) {
                            var rvaNotes: [String] = []
                            if p.getRVA > 0 { rvaNotes.append(String(format: "get RVA: 0x%llX", p.getRVA)) }
                            if p.setRVA > 0 { rvaNotes.append(String(format: "set RVA: 0x%llX", p.setRVA)) }
                            try writer.writeLine("\t// \(rvaNotes.joined(separator: " | "))")
                        }
                        var accessors: [String] = []
                        if p.getMethodIndex >= 0 { accessors.append("get;") }
                        if p.setMethodIndex >= 0 { accessors.append("set;") }
                        if accessors.isEmpty { accessors.append("get;") }
                        try writer.writeLine("\tpublic \(p.typeName) \(p.name) { \(accessors.joined(separator: " ")) }")
                    }
                    try writer.writeLine("")
                }

                if !t.events.isEmpty {
                    try writer.writeLine("\t// Events")
                    for ev in t.events {
                        if options.restoreAttributes {
                            for attr in ev.attributes {
                                try writer.writeLine("\t[\(attr.name)]")
                            }
                        }
                        try writer.writeLine("\tpublic event \(ev.typeName) \(ev.name);")
                    }
                    try writer.writeLine("")
                }

                if options.includeMethods && !t.methods.isEmpty {
                    try writer.writeLine("\t// Methods")
                    for m in t.methods {
                        if options.restoreAttributes {
                            for attr in m.attributes {
                                try writer.writeLine("\t[\(attr.name)]")
                            }
                        }
                        if options.writeMethodOffsets {
                            let rvaStr = "0x" + String(m.rva, radix: 16, uppercase: true)
                            let offStr = "0x" + String(m.fileOffset, radix: 16, uppercase: true)
                            let vaStr = "0x" + String(m.va, radix: 16, uppercase: true)
                            let slotStr = m.slot != 0xFFFF ? " Slot: \(m.slot)" : ""
                            let semStr = m.arm64Semantics.isEmpty ? "" : " | \(m.arm64Semantics)"
                            try writer.writeLine("\t// RVA: \(rvaStr) Offset: \(offStr) VA: \(vaStr)\(slotStr)\(semStr)")
                            if m.genericInstRVAs.count > 1 {
                                let genList = m.genericInstRVAs.map { "0x" + String($0, radix: 16, uppercase: true) }.joined(separator: ", ")
                                try writer.writeLine("\t// GenericInst RVAs (\(m.genericInstRVAs.count)): \(genList)")
                            }
                        }
                        let mVis = methodVisibility(m.flags)
                        var mMods = ""
                        if (m.flags & 0x0010) != 0 { mMods += "static " }
                        else if (m.flags & 0x0400) != 0 { mMods += "abstract " }
                        else if (m.flags & 0x0040) != 0 { mMods += "virtual " }
                        let genSuffix = m.genericParamNames.isEmpty ? "" : "<\(m.genericParamNames.joined(separator: ", "))>"
                        let paramText = m.parameters.map { p in
                            var prefix = ""
                            if p.isOut { prefix = "out " }
                            else if p.isRef { prefix = "ref " }
                            let def = p.defaultValue.map { " = \($0)" } ?? ""
                            return "\(prefix)\(p.typeName) \(p.name)\(def)"
                        }.joined(separator: ", ")
                        try writer.writeLine("\t\(mVis) \(mMods)\(m.returnTypeName) \(m.name)\(genSuffix)(\(paramText)) { }")
                        try writer.writeLine("")
                    }
                }

                try writer.writeLine("}")
                try writer.writeLine("")
            }
        }

        // Plaintext Mach-O Multi-Binary section (Obj-C / Swift / Native Symbols)
        let effectiveSnapshots: [NativeBinarySnapshot] = !snapshots.isEmpty ? snapshots : (macho.map { [$0.makeSnapshot()] } ?? [])
        if options.deepMachOScan {
            for bin in effectiveSnapshots {
                let hasNative = !bin.objcClasses.isEmpty
                    || !bin.swiftTypes.isEmpty
                    || (types.isEmpty && (!bin.exportedSymbols.isEmpty || !bin.symtabSymbols.isEmpty || !bin.functionStartsRVA.isEmpty || !bin.xrefFunctions.isEmpty))
                guard hasNative else { continue }

                try writer.writeLine("// ============================================================")
                try writer.writeLine("// Binary: \(bin.sourceName) (\(bin.architecture)) BaseVM=0x\(String(bin.baseVM, radix: 16, uppercase: true))")
                try writer.writeLine("// ============================================================")

                if !bin.objcClasses.isEmpty {
                    try writer.writeLine("// --- Objective-C Classes (\(bin.objcClasses.count)) ---")
                    for cls in bin.objcClasses {
                        try writer.writeLine("// Obj-C Class: \(cls.name) : \(cls.superName)")
                        try writer.writeLine("public class \(cls.name) : \(cls.superName)")
                        try writer.writeLine("{")
                        if options.includeFields {
                            for iv in cls.ivars {
                                let offStr = options.writeFieldOffsets ? (" // 0x" + String(UInt32(bitPattern: iv.offset), radix: 16, uppercase: true)) : ""
                                try writer.writeLine("\tprivate \(iv.typeEncoding.isEmpty ? "IntPtr" : iv.typeEncoding) \(iv.name);\(offStr)")
                            }
                        }
                        if options.includeProperties {
                            for pr in cls.properties {
                                try writer.writeLine("\tpublic object \(pr.name) { get; set; } // \(pr.attributes)")
                            }
                        }
                        if options.includeMethods {
                            for m in cls.methods {
                                if options.writeMethodOffsets {
                                    try writer.writeLine("\t// RVA: 0x\(String(m.rva, radix: 16, uppercase: true)) Offset: 0x\(String(m.fileOffset, radix: 16, uppercase: true)) VA: 0x\(String(m.va, radix: 16, uppercase: true))")
                                }
                                let prefix = m.isClassMethod ? "static " : ""
                                try writer.writeLine("\tpublic \(prefix)void \(m.name)() { } // \(m.types)")
                            }
                        }
                        try writer.writeLine("}")
                        try writer.writeLine("")
                    }
                }

                if !bin.swiftTypes.isEmpty {
                    try writer.writeLine("// --- Swift 5 Descriptors (\(bin.swiftTypes.count)) ---")
                    for st in bin.swiftTypes {
                        try writer.writeLine("// RVA: 0x\(String(st.descriptorRVA, radix: 16, uppercase: true))")
                        if st.fields.isEmpty {
                            try writer.writeLine("public \(st.kind) \(st.name) { }")
                        } else {
                            try writer.writeLine("public \(st.kind) \(st.name)")
                            try writer.writeLine("{")
                            for fname in st.fields {
                                try writer.writeLine("\tpublic var \(fname);")
                            }
                            try writer.writeLine("}")
                        }
                    }
                    try writer.writeLine("")
                }

                if types.isEmpty {
                    if !bin.exportedSymbols.isEmpty {
                        try writer.writeLine("// --- DYLD Exports (\(bin.exportedSymbols.count)) ---")
                        for sym in bin.exportedSymbols {
                            try writer.writeLine("// RVA: 0x\(String(sym.rva, radix: 16, uppercase: true)) Offset: 0x\(String(sym.fileOffset, radix: 16, uppercase: true)) VA: 0x\(String(sym.va, radix: 16, uppercase: true)) | \(sym.name)")
                        }
                        try writer.writeLine("")
                    }
                    if !bin.symtabSymbols.isEmpty {
                        try writer.writeLine("// --- Symtab Symbols (\(bin.symtabSymbols.count)) ---")
                        for sym in bin.symtabSymbols {
                            try writer.writeLine("// RVA: 0x\(String(sym.rva, radix: 16, uppercase: true)) Offset: 0x\(String(sym.fileOffset, radix: 16, uppercase: true)) VA: 0x\(String(sym.va, radix: 16, uppercase: true)) | \(sym.name)")
                        }
                        try writer.writeLine("")
                    }
                    if !bin.xrefFunctions.isEmpty {
                        try writer.writeLine("// --- ARM64 String XRefs (\(bin.xrefFunctions.count)) ---")
                        for xr in bin.xrefFunctions {
                            try writer.writeLine("// RVA: 0x\(String(xr.rva, radix: 16, uppercase: true)) Offset: 0x\(String(xr.fileOffset, radix: 16, uppercase: true)) VA: 0x\(String(xr.va, radix: 16, uppercase: true)) | \(xr.name)")
                        }
                        try writer.writeLine("")
                    }
                    var covered = Set<UInt64>()
                    for s in bin.exportedSymbols { covered.insert(s.rva) }
                    for s in bin.symtabSymbols { covered.insert(s.rva) }
                    for c in bin.objcClasses { for m in c.methods { covered.insert(m.rva) } }
                    let uncovered = bin.functionStartsRVA.filter { $0 > 0 && !covered.contains($0) }
                    if !uncovered.isEmpty {
                        try writer.writeLine("// --- Uncovered Function Starts (\(uncovered.count)) ---")
                        for rva in uncovered {
                            let va = bin.baseVM + rva
                            let rHex = String(rva, radix: 16, uppercase: true)
                            let vHex = String(va, radix: 16, uppercase: true)
                            try writer.writeLine("// RVA: 0x\(rHex) VA: 0x\(vHex) | sub_\(rHex)")
                        }
                        try writer.writeLine("")
                    }
                }
            }
        }

        try writer.close()
    }

    private static func visibilityKeyword(_ flags: UInt32, isNested: Bool) -> String {
        let vis = flags & 0x07
        if isNested {
            switch vis {
            case 2: return "public"
            case 3: return "private"
            case 4: return "protected"
            case 5: return "internal"
            case 6, 7: return "protected internal"
            default: return "private"
            }
        }
        return vis == 1 ? "public" : "internal"
    }

    private static func fieldVisibility(_ attrs: UInt16) -> String {
        switch attrs & 0x07 {
        case 6: return "public"
        case 4: return "protected"
        case 3: return "internal"
        case 5: return "protected internal"
        default: return "private"
        }
    }

    private static func methodVisibility(_ flags: UInt16) -> String {
        switch flags & 0x07 {
        case 6: return "public"
        case 4: return "protected"
        case 3: return "internal"
        case 5: return "protected internal"
        default: return "private"
        }
    }
}
